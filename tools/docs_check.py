"""Checks that keep the docs true and small (docs/notes/claude-code.md, "The docs check").

Run from the repo root: python -I tools/docs_check.py. Prints each problem and exits 1 if there are any; test.ps1
runs it after the tests. The limits are the ones .claude/rules/docs.md states; each is written once, here.
The commit hook (tools/hooks/claude_hooks.py) uses is_code and covering_docs, so "code" and "its notes file" mean
the same in both.
"""

import json
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
KILOBYTE = 1024

# What loads into every session stays small; a reference file past its budget splits by topic.
BUDGETS_KB = [
    (re.compile(r"^CLAUDE\.md$"), 8),
    (re.compile(r"^\.claude/(rules/[^/]+|skills/[^/]+/SKILL)\.md$"), 4),
    (re.compile(r"^README\.md$"), 8),
    (re.compile(r"^docs/(guides|notes)/[^/]+\.md$"), 20),
]

# Files that are others' (vendored unmodified), made by a tool, or pictures and sounds: no notes file describes
# them line by line, and the commit hook doesn't remind about them.
NOT_OURS = (
    "docs/", "external/", "static/katex-", "static/jitsi-rnnoise-", "static/workadventure-ns-", "static/flags-",
    "static/livekit-client-", "static/icons/", "static/emoji.json", "static/changelog.json", "static/js/icon-shapes.js",
    "mobile/src/icon-shapes.js", "mobile/assets/", "desktop/src-tauri/icons/",
    "desktop/src-tauri/permissions/autogenerated/", "icon/", "seasonal/",
)
CODE_EXTENSIONS = (
    ".py", ".js", ".html", ".css", ".ps1", ".bat", ".rs", ".kt", ".java", ".json", ".toml", ".yaml", ".yml", ".xml",
    ".ini", ".txt", ".env", ".example", ".gradle", ".properties",
)
# Lock files change with every package update and say nothing a note describes.
LOCK_FILES = ("package-lock.json", "Cargo.lock")

# A backticked name that looks like one of our files: checked to exist somewhere in the repo.
FILE_NAME = re.compile(r"^[\w.-]+(/[\w.-]+)*\.(py|js|ps1|md|html|css|rs|kt|bat|yaml|toml)$")

# Files the docs may name that git never holds: secrets, databases, logs, made at run time.
NOT_IN_GIT = {"latest.json", "chat.log", "chat.out.log", "voice.log", "ai.log", "bot.log", "bot.errors.log",
              "backup.log", "fetch.log", "CLAUDE.local.md", "rnnoise-sync.js"}

# A reference to a section: `voice.py, "Calls in DMs and group DMs"` or running.md, "Updating".
SECTION_REFERENCE = re.compile(r"`?([\w-]+\.(py|md))`?,\s*\"([^\"\n]{2,80})\"")

# An inline link [text](target), its target in <> when it holds spaces.
LINK = re.compile(r"\]\(<?([^)>\s]+)>?(?:\s+\"[^\"]*\")?\)")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")

# Our own addresses stay out of the guides, written for anyone hosting a copy (.claude/rules/docs.md). The README
# may say where the original runs.
PUBLIC_DOCS = re.compile(r"^docs/guides/.+\.md$")
OWN_DOMAIN = re.compile(r"datslok\.no", re.IGNORECASE)


def tracked_files(root=ROOT):
    """Every file git has or would add (tracked, or new and not ignored), with / as the separator."""
    result = subprocess.run(["git", "-C", str(root), "ls-files", "--cached", "--others", "--exclude-standard"],
                            capture_output=True, encoding="utf-8", errors="replace")
    return sorted({line for line in result.stdout.splitlines() if line and (root / line).exists()})


def is_code(path):
    """Whether a file is our code, which a notes file's Covers: line should claim."""
    if path.endswith(".md") or path.startswith(NOT_OURS) or path.rsplit("/", 1)[-1] in LOCK_FILES:
        return False
    return path.startswith(".claude/") or path.endswith(CODE_EXTENSIONS)


def covers_line(text):
    """The paths a notes file's Covers: line names, or []."""
    for line in text.splitlines():
        if line.startswith("Covers:"):
            return re.findall(r"`([^`]+)`", line)
    return []


def covering_docs(root=ROOT):
    """Each Covers: prefix, mapped to the notes file that claims it."""
    covering = {}
    for doc in sorted((root / "docs" / "notes").glob("*.md")):
        for prefix in covers_line(doc.read_text(encoding="utf-8", errors="replace")):
            covering[prefix] = "docs/notes/" + doc.name
    return covering


def describing_doc(path, covering):
    """The notes file with the longest Covers: prefix of this path, or None."""
    prefixes = [prefix for prefix in covering if path.startswith(prefix)]
    return covering[max(prefixes, key=len)] if prefixes else None


def markdown_files(files):
    return [path for path in files if path.endswith(".md") and not path.startswith("external/")]


def read(root, path):
    return (root / path).read_text(encoding="utf-8", errors="replace")


def prose(text):
    """A doc's text without fenced code blocks: commands and examples there aren't checked."""
    return re.sub(r"^```.*?^```", "", text, flags=re.MULTILINE | re.DOTALL)


def slug(heading):
    """The anchor GitHub gives a heading: lower case, punctuation dropped, spaces as hyphens."""
    text = re.sub(r"`|\*\*|\*|_(?=\w)|(?<=\w)_", "", heading.strip().lower())
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def anchors(text):
    """Every heading's anchor in a doc, with GitHub's -1, -2 for repeats."""
    seen, result = {}, set()
    for line in prose(text).splitlines():
        match = HEADING.match(line)
        if match:
            base = slug(match.group(2))
            count = seen.get(base, 0)
            seen[base] = count + 1
            result.add(base if count == 0 else f"{base}-{count}")
    return result


def headings(text):
    return {HEADING.match(line).group(2).strip() for line in prose(text).splitlines() if HEADING.match(line)}


# ---------- The checks: each returns a list of problems ----------

def check_budgets(root, files):
    problems = []
    for path in markdown_files(files):
        for pattern, budget in BUDGETS_KB:
            size = len(read(root, path).encode("utf-8"))
            if pattern.match(path) and size > budget * KILOBYTE:
                problems.append(f"{path}: {size / KILOBYTE:.1f} KB, over its {budget} KB budget: split it by topic "
                                f"(compact-docs skill)")
    return problems


def check_links(root, files):
    problems = []
    for path in markdown_files(files):
        text = read(root, path)
        for target in LINK.findall(prose(text)):
            if re.match(r"^[a-z][a-z+.-]*:", target):  # https:, mailto:: out of the repo
                continue
            file_part, _, anchor = unquote(target).partition("#")
            linked = (root / path).parent / file_part if file_part else root / path
            if file_part.startswith("/"):
                linked = root / file_part.lstrip("/")
            if not linked.exists():
                problems.append(f"{path}: a link to {target}, which doesn't exist")
            elif anchor and linked.suffix == ".md" and anchor not in anchors(linked.read_text(encoding="utf-8")):
                problems.append(f"{path}: a link to {target}, but {linked.name} has no such heading")
    return problems


def check_file_names(root, files):
    """Each backticked file name in a doc is a file in the repo (by its end: `src/voice.js` is mobile's)."""
    problems = []
    ends = set()
    for file in files:
        parts = file.split("/")
        ends.update("/".join(parts[i:]) for i in range(len(parts)))
    for path in markdown_files(files):
        for number, line in enumerate(prose(read(root, path)).splitlines(), 1):
            for name in re.findall(r"`([^`\n]+)`", line):
                name = name.strip()
                if FILE_NAME.match(name) and name not in ends and name.rsplit("/", 1)[-1] not in NOT_IN_GIT:
                    problems.append(f"{path}:{number}: `{name}` isn't a file in the repo (renamed or deleted?)")
    return problems


def check_section_references(root, files):
    """`voice.py, "Calls"` names a # ---------- Calls ---------- section; running.md, "Updating" a heading."""
    problems = []
    by_name = {}
    for file in files:
        by_name.setdefault(file.rsplit("/", 1)[-1], []).append(file)
    for path in markdown_files(files):
        for number, line in enumerate(prose(read(root, path)).splitlines(), 1):
            for name, kind, section in SECTION_REFERENCE.findall(line):
                candidates = by_name.get(name, [])
                if not candidates:
                    continue  # a file name check's business
                if kind == "py":
                    found = any(re.search(rf"^\s*# -+ {re.escape(section)} -+\s*$", read(root, file), re.MULTILINE)
                                for file in candidates)
                else:
                    found = any(section in headings(read(root, file)) for file in candidates)
                if not found:
                    problems.append(f"{path}:{number}: {name} has no section \"{section}\"")
    return problems


def check_covers(root, files):
    """Every code file is claimed by a notes file's Covers: line, and every claimed path exists."""
    covering = covering_docs(root)
    problems = [f"{doc}: its Covers: line names {prefix}, which matches no file"
                for prefix, doc in covering.items() if not any(file.startswith(prefix) for file in files)]
    uncovered = [file for file in files if is_code(file) and describing_doc(file, covering) is None]
    problems += [f"{file}: no docs/notes file's Covers: line claims it" for file in uncovered]
    return problems


def check_notes_index(root, files):
    claude = read(root, "CLAUDE.md")
    return [f"CLAUDE.md: the notes index doesn't list {path}" for path in files
            if re.match(r"^docs/notes/[^/]+\.md$", path) and f"]({path})" not in claude]


def check_scripts_listed(root, files):
    """Every script is in docs/guides/scripts.md, "Scripts at a glance"."""
    listed = read(root, "docs/guides/scripts.md")
    return [f"docs/guides/scripts.md doesn't mention {path}" for path in files
            if re.match(r"^scripts/.+\.(ps1|bat)$", path) and path.rsplit("/", 1)[-1] not in listed]


def check_public_docs(root, files):
    """The guides and README are for anyone hosting a copy: example.com, never our own domain."""
    problems = []
    for path in files:
        if PUBLIC_DOCS.match(path):
            for number, line in enumerate(read(root, path).splitlines(), 1):
                if OWN_DOMAIN.search(line):
                    problems.append(f"{path}:{number}: our own domain in a public guide (use example.com)")
    return problems


def check_claude_files(root, files):
    """Rules load by their paths:, skills by their name and description."""
    problems = []
    for path in files:
        # Claude Code reads any CLAUDE.md as a folder's instructions, and Windows ignores case: a notes file named
        # claude.md would load as rules.
        if path.rsplit("/", 1)[-1].lower() == "claude.md" and path != "CLAUDE.md":
            problems.append(f"{path}: Claude Code would load it as that folder's instructions: rename it")
        text = read(root, path) if path.endswith(".md") else ""
        if re.match(r"^\.claude/rules/[^/]+\.md$", path) and not re.match(r"^---\n(.*\n)*?paths:\n", text):
            problems.append(f"{path}: no paths: in its front matter, so it would load in every session")
        match = re.match(r"^\.claude/skills/([^/]+)/SKILL\.md$", path)
        if match:
            if not re.search(rf"^name: {re.escape(match.group(1))}$", text, re.MULTILINE):
                problems.append(f"{path}: its name: isn't its folder's name, {match.group(1)}")
            if not re.search(r"^description: .{20,}", text, re.MULTILINE):
                problems.append(f"{path}: no description: saying when to use it")
    return problems


def check_changelog(root, files):
    try:
        data = json.loads(read(root, "static/changelog.json"))
    except ValueError as error:
        return [f"static/changelog.json isn't valid JSON: {error}"]
    if not isinstance(data.get("features"), list) or not isinstance(data.get("changes"), list):
        return ["static/changelog.json needs a features list and a changes list"]
    return []


CHECKS = [check_budgets, check_links, check_file_names, check_section_references, check_covers, check_notes_index,
          check_scripts_listed, check_public_docs, check_claude_files, check_changelog]


def problems(root=ROOT):
    files = tracked_files(root)
    return [problem for check in CHECKS for problem in check(root, files)]


if __name__ == "__main__":
    found = problems()
    for problem in found:
        print(problem)
    print(f"Docs check: {len(found)} problem(s)." if found else "Docs check: all good.")
    sys.exit(1 if found else 0)
